// Writes src/core/palette-data.ts from a Tailwind v4 theme.css.
// Usage: node scripts/make-palette.mjs <path/to/tailwindcss/theme.css>
// Reword doesn't depend on Tailwind; point this at any installed copy.
import fs from 'node:fs';
import path from 'node:path';

const themePath = process.argv[2];
if (!themePath) {
  console.error('Usage: node scripts/make-palette.mjs <path/to/tailwindcss/theme.css>');
  process.exit(1);
}

const css = fs.readFileSync(themePath, 'utf8');
let version = 'unknown';
try {
  version = JSON.parse(fs.readFileSync(path.join(path.dirname(themePath), 'package.json'), 'utf8')).version;
} catch {}

const STEPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
const palette = {};
for (const [, family, step, value] of css.matchAll(/--color-([a-z]+)-(\d+):\s*(oklch\([^)]*\))/g)) {
  if (!STEPS.includes(step)) continue;
  (palette[family] ??= {})[step] = value;
}

const families = Object.keys(palette).filter((f) => STEPS.every((s) => palette[f][s]));
const body = families
  .map((f) => `  ${f}: {\n${STEPS.map((s) => `    "${s}": "${palette[f][s]}",`).join('\n')}\n  },`)
  .join('\n');

const out = `// Generated by scripts/make-palette.mjs from tailwindcss@${version} theme.css. Don't edit by hand.
export const STEPS = ${JSON.stringify(STEPS)} as const;
export type Step = (typeof STEPS)[number];

/** Tailwind's stock color families, as the OKLCH strings its theme defines. */
export const STOCK_PALETTE: Record<string, Record<Step, string>> = {
${body}
};
`;
const target = path.resolve(import.meta.dirname, '../src/core/palette-data.ts');
fs.writeFileSync(target, out);
console.log(`Wrote ${families.length} families from tailwindcss@${version} to ${path.relative(process.cwd(), target)}`);
